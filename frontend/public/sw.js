// Service worker do Forja: deixa o app instalavel e abre mesmo com sinal fraco na academia.
const CACHE = 'forja-v1'

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(['/'])).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  const url = new URL(req.url)
  if (req.method !== 'GET' || url.origin !== location.origin) return
  if (url.pathname.startsWith('/api/')) return // dados sempre vem da rede
  const immutable = url.pathname.startsWith('/assets/') || url.pathname.startsWith('/ex/')
  if (immutable) {
    // Arquivos versionados e fotos: cache primeiro
    event.respondWith(
      caches.match(req).then((hit) => hit || fetch(req).then((res) => {
        const copy = res.clone()
        caches.open(CACHE).then((c) => c.put(req, copy))
        return res
      })),
    )
    return
  }
  // Pagina e demais arquivos: rede primeiro, cache como reserva
  event.respondWith(
    fetch(req).then((res) => {
      const copy = res.clone()
      caches.open(CACHE).then((c) => c.put(req, copy))
      return res
    }).catch(() => caches.match(req).then((hit) => hit || caches.match('/'))),
  )
})
